export default function Reports() {
  const showToast = useToast();
  const navigate = useNavigate();
  const { can } = useAuth();

  const [tab, setTab] = useState('attendance');
  // Shared with My Classes, Attendance and Marks — one request between them.
  const { data: classes } = useFacultyClasses();
  const [classKey, setClassKey] = useState('all');
  const [dateFrom, setDateFrom] = useState('');
  const [dateTo, setDateTo] = useState('');
  const [query, setQuery] = useState('');
  const [exporting, setExporting] = useState('');

  const [report, setReport] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  const selectedClass = useMemo(
    () => classes.find((c) => c.key === classKey) || null,
    [classes, classKey],
  );

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await facultyApi.report({
        type: tab,
        subject_id: selectedClass?.subject_id,
        section_id: selectedClass?.section_id,
        date_from: tab === 'attendance' ? dateFrom : undefined,
        date_to: tab === 'attendance' ? dateTo : undefined,
      });
      setReport(res?.data || null);
    } catch (err) {
      setError(err.message || 'Could not generate this report.');
      setReport(null);
    } finally {
      setLoading(false);
    }
  }, [tab, selectedClass, dateFrom, dateTo]);

  useEffect(() => { load(); }, [load]);

  const active = CONFIG[tab];

  // Search is applied to the generated rows rather than sent to the server:
  // the report is already scoped to this teacher, so this is only narrowing.
  const rows = useMemo(() => {
    const all = report?.rows || [];
    const q = query.trim().toLowerCase();
    if (!q) return all;
    return all.filter((r) => Object.values(r).some(
      (v) => v !== null && v !== undefined && String(v).toLowerCase().includes(q),
    ));
  }, [report, query]);

  const handleExport = (format) => {
    if (!rows.length) {
      showToast('There is nothing to export in this report.');
      return;
    }

    setExporting(format);
    const filename = `${active.title.replace(/\s+/g, '_').toLowerCase()}.`;
    const exportRows = rows.map(active.toRow);

    const scope = report?.scope;
    const subtitle = [
      report?.teacher ? `Teacher: ${report.teacher}` : null,
      scope?.classes?.length ? `Classes: ${scope.classes.join(', ')}` : null,
      scope?.date_from || scope?.date_to
        ? `Period: ${scope.date_from ? fmtDateShort(scope.date_from) : 'start'} – ${scope.date_to ? fmtDateShort(scope.date_to) : 'today'}`
        : null,
      `${exportRows.length} records`,
      report?.generated_at ? `Generated ${new Date(report.generated_at).toLocaleString()}` : null,
    ].filter(Boolean).join(' · ');

    setTimeout(() => {
      if (format === 'csv') exportCSV(`${filename}csv`, active.headers, exportRows);
      if (format === 'xlsx') exportExcel(`${filename}xlsx`, active.title, active.headers, exportRows);
      if (format === 'pdf') {
        exportPDF(`${filename}pdf`, {
          title: active.title,
          subtitle,
          headers: active.headers,
          rows: exportRows,
        });
      }
      setExporting('');
      showToast(`${active.title} exported as ${format.toUpperCase()}`);
    }, 200);
  };

  if (!can('view_reports')) {
    return (
      <Layout title="Reports">
        <div className="empty-state">You do not have permission to view reports.</div>
      </Layout>
    );
  }

  return (
    <Layout title="Reports">
      <div className="reports-head">
        <div>
          <h2>Reports</h2>
          <p>
            Attendance · Marks · Grades · Assignments · Performance · Class Summary —
            generated from your own classes and exportable to Excel, PDF or CSV
          </p>
        </div>
        <div className="attendance-export-group">
          <button className="btn btn-outline" disabled={exporting === 'xlsx' || loading} onClick={() => handleExport('xlsx')}>
            <FileSpreadsheet size={14} /> {exporting === 'xlsx' ? 'Exporting…' : 'Excel'}
          </button>
          <button className="btn btn-outline" disabled={exporting === 'pdf' || loading} onClick={() => handleExport('pdf')}>
            <FileText size={14} /> {exporting === 'pdf' ? 'Exporting…' : 'PDF'}
          </button>
          <button className="btn btn-outline" disabled={exporting === 'csv' || loading} onClick={() => handleExport('csv')}>
            <FileType2 size={14} /> {exporting === 'csv' ? 'Exporting…' : 'CSV'}
          </button>
        </div>
      </div>

      <div className="reports-tabs">
        {REPORT_TABS.map((t) => (
          <button
            key={t.key}
            className={`reports-tab${tab === t.key ? ' active' : ''}`}
            onClick={() => setTab(t.key)}
          >
            {t.label}
          </button>
        ))}
      </div>

      <FilterBar
        resetActive={classKey !== 'all' || !!query || !!dateFrom || !!dateTo}
        onReset={() => { setClassKey('all'); setQuery(''); setDateFrom(''); setDateTo(''); }}
      >
        <FilterInput label="Search" placeholder="Any field in this report" value={query} onChange={(e) => setQuery(e.target.value)} />
        <FilterSelect
          label="Class"
          value={classKey}
          onChange={(e) => setClassKey(e.target.value)}
          allLabel="All My Classes"
          options={classes.map((c) => ({
            value: c.key,
            label: `${c.subject_code} · Sec ${c.section_name}`,
          }))}
        />
        {tab === 'attendance' && (
          <>
            <FilterDate label="Date From" value={dateFrom} onChange={(e) => setDateFrom(e.target.value)} />
            <FilterDate label="Date To" value={dateTo} onChange={(e) => setDateTo(e.target.value)} />
          </>
        )}
      </FilterBar>

      <div className="reports-count">
        {loading ? 'Generating…' : `${rows.length} records`}
        {report?.scope?.classes?.length ? ` · ${report.scope.classes.join(', ')}` : ''}
        {' · '}
        <Download size={12} style={{ verticalAlign: -1 }} /> Export to Excel, PDF or CSV
      </div>

      <DataGate loading={loading} error={error} onRetry={load} label="Generating report…">
        {/* A report with no rows because the underlying records do not exist
            reads identically to one that failed to load, so the reason is
            spelled out with the action that would fill it. A search that
            matched nothing is a different case and keeps the plain message. */}
        {rows.length === 0 && !query && active.empty ? (
          <div className="empty-state">
            <p style={{ margin: 0 }}>{active.empty}</p>
            {active.emptyAction && (
              <button
                type="button"
                className="btn btn-outline"
                style={{ marginTop: '0.9rem' }}
                onClick={() => navigate(active.emptyAction.to)}
              >
                {active.emptyAction.label}
              </button>
            )}
          </div>
        ) : (
          <DataTable
            columns={active.columns}
            rows={rows}
            rowKey="id"
            searchable={false}
            emptyMessage="No records match your search in this report."
          />
        )}
      </DataGate>
    </Layout>
  );
}
