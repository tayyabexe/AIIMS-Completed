/*
 * Every table here is generated by GET /api/faculty/reports, so the screen and
 * the export cannot disagree and a report is not limited to whatever the
 * browser happened to have downloaded. The seven tabs used to be computed in
 * the browser from `marks`, `submissions` and `fees` — collections the loader
 * left empty for a teacher — so five of them were permanently blank.
 *
 * Two are gone rather than kept as empty tables:
 *   Fee Reports        - teachers are refused the fee endpoints by design.
 *   Teacher Performance - it listed every colleague from a directory the
 *                        teacher cannot read; "Class Summary" is the same
 *                        question asked about their own classes.
 */

