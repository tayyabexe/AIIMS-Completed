/*
 * Notification emission.
 *
 * WHY THIS EXISTS
 * ---------------
 * `notifications` was a read-only table. Every portal had a Notifications page,
 * a bell and an unread badge reading from it, and nothing in the entire backend
 * ever wrote a row — a grep for `Notification.create`, `bulkCreate` and
 * `INSERT INTO notifications` returned nothing. The only rows present came from
 * a database dump and were all dated 2024, which is why a teacher opening the
 * page landed on "You're all caught up" and an admin saw a single read notice
 * from January. The screens were correct; the table had simply stopped growing.
 *
 * This module is the missing half. Controllers call it at the moment an event
 * actually happens, and it works out who is affected and what each of them
 * should read.
 *
 * WHY IT IS NOT PART OF auditService
 * ----------------------------------
 * The two look similar and are opposites in the way that matters: the audit
 * trail records ONE row describing the ACTOR ("admin #7 published this
 * result"), kept forever, readable only by administrators. A notification is N
 * rows addressed to the people AFFECTED ("your result is out") — never the
 * actor — dismissible, and scoped to each recipient's own account. Deriving one
 * from the other would force whichever came second to distort: audit rows have
 * no recipient list, and notification rows must not name the staff member who
 * caused them.
 *
 * WHY IT IS NOT ANNOUNCEMENTS EITHER
 * ----------------------------------
 * An announcement is one row broadcast to a role, authored by a person, with no
 * per-reader state; it lives on the Announcements screen. A notification is
 * addressed to one account, generated by an event, and carries `is_read`. They
 * are deliberately kept in separate tables behind separate screens, so nothing
 * here ever emits an announcement and nothing here reads one.
 *
 * FAILURE BEHAVIOUR
 * -----------------
 * Emitting never throws and never blocks the act it describes, for the same
 * reason auditService.record() doesn't: refusing to publish a result because
 * the notifications table was locked would be a far worse outcome than a
 * missing notice. Errors go to the console and the caller proceeds. Callers
 * should therefore NOT await this inside a transaction that the act depends on.
 */

