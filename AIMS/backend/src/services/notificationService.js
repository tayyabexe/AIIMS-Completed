// ---------------------------------------------------------------- audiences

/*
 * Every account that should hear about something happening to one student:
 * the student's own login, plus each linked guardian.
 *
 * `students.user_id` is nullable — a student admitted before their account was
 * provisioned has none — and a guardian link may point at a soft-deleted
 * parent, so both are filtered here rather than producing rows addressed to
 * nobody. Deactivated and deleted users are excluded for the same reason:
 * a notification for an account that cannot sign in is never read and still
 * counts against the unread badge of nobody.
 *
 * The student's name rides along on both branches. A guardian's copy has to be
 * worded in the third person ("Ali's result is out", not "your result"), and
 * carrying the name on a join the query is already doing is cheaper than every
 * caller looking it up separately just to phrase one sentence.
 */
const studentAudience = async (studentId) => {
    if (!studentId) return [];

    return sequelize.query(
        `SELECT u.user_id, u.role_id, s.first_name, s.last_name
           FROM students s
           JOIN users u ON u.user_id = s.user_id
          WHERE s.student_id = :studentId
            AND s.is_deleted = 0
            AND u.is_active = 1
            AND u.is_deleted = 0

          UNION

         SELECT u.user_id, u.role_id, s.first_name, s.last_name
           FROM student_guardians sg
           JOIN students s ON s.student_id = sg.student_id
           JOIN parents p ON p.parent_id = sg.parent_id
           JOIN users u ON u.user_id = p.user_id
          WHERE sg.student_id = :studentId
            AND s.is_deleted = 0
            AND p.is_deleted = 0
            AND u.is_active = 1
            AND u.is_deleted = 0`,
        { ...SELECT, replacements: { studentId } }
    );
};

/** The student's own account only — used where a guardian has no stake. */
const studentOnlyAudience = async (studentId) => {
    if (!studentId) return [];

    return sequelize.query(
        `SELECT u.user_id, u.role_id, s.first_name, s.last_name
           FROM students s
           JOIN users u ON u.user_id = s.user_id
          WHERE s.student_id = :studentId
            AND s.is_deleted = 0
            AND u.is_active = 1
            AND u.is_deleted = 0`,
        { ...SELECT, replacements: { studentId } }
    );
};

/*
 * A teacher's login. `teachers` holds no user_id of its own — the person is an
 * `employees` row and the account hangs off that — so this is a two-hop join
 * and not the one-liner it looks like it should be.
 */
const teacherAudience = async (teacherId) => {
    if (!teacherId) return [];

    return sequelize.query(
        `SELECT u.user_id, u.role_id
           FROM teachers t
           JOIN employees e ON e.employee_id = t.employee_id
           JOIN users u ON u.user_id = e.user_id
          WHERE t.teacher_id = :teacherId
            AND t.is_deleted = 0
            AND e.is_deleted = 0
            AND u.is_active = 1
            AND u.is_deleted = 0`,
        { ...SELECT, replacements: { teacherId } }
    );
};

/** One named account, by user id. */
const userAudience = async (userId) => {
    if (!userId) return [];

    return sequelize.query(
        `SELECT user_id, role_id
           FROM users
          WHERE user_id = :userId
            AND is_active = 1
            AND is_deleted = 0`,
        { ...SELECT, replacements: { userId } }
    );
};

/*
 * Staff who need to act on something.
 *
 * Defaults to administrators. Fee events pass the accountant role as well,
 * because a payment a parent has declared sits unverified until someone in the
 * accounts office looks at it, and they are the ones who do.
 */
const staffAudience = async (roleIds = [ROLES.SUPER_ADMIN, ROLES.ADMIN]) => {
    if (!roleIds.length) return [];

    return sequelize.query(
        `SELECT user_id, role_id
           FROM users
          WHERE role_id IN (:roleIds)
            AND is_active = 1
            AND is_deleted = 0`,
        { ...SELECT, replacements: { roleIds } }
    );
};

/*
 * Every student currently taking a subject, plus their guardians.
 *
 * Used for events that belong to a class rather than a person — an exam being
 * scheduled, a timetable slot moving. Restricted to Active enrolments so a
 * student who dropped the subject is not told about its exam.
 */
const subjectAudience = async (subjectId, semesterId) => {
    if (!subjectId) return [];

    const semesterClause = semesterId ? "AND e.semester_id = :semesterId" : "";

    return sequelize.query(
        `SELECT u.user_id, u.role_id
           FROM enrollments e
           JOIN students s ON s.student_id = e.student_id
           JOIN users u ON u.user_id = s.user_id
          WHERE e.subject_id = :subjectId
            ${semesterClause}
            AND e.status = 'Active'
            AND s.is_deleted = 0
            AND u.is_active = 1
            AND u.is_deleted = 0

          UNION

         SELECT u.user_id, u.role_id
           FROM enrollments e
           JOIN student_guardians sg ON sg.student_id = e.student_id
           JOIN parents p ON p.parent_id = sg.parent_id
           JOIN users u ON u.user_id = p.user_id
          WHERE e.subject_id = :subjectId
            ${semesterClause}
            AND e.status = 'Active'
            AND p.is_deleted = 0
            AND u.is_active = 1
            AND u.is_deleted = 0`,
        { ...SELECT, replacements: { subjectId, semesterId } }
    );
};

// ------------------------------------------------------------------- emit

/*
 * Resolves a per-recipient field.
 *
 * Wording usually has to differ by role even though the event is one event:
 * the student reads "Your result for Spring 2024 has been published" and their
 * father reads "Ali's result for Spring 2024 has been published". Passing a
 * function keeps both versions of that sentence at the call site, next to each
 * other, instead of in two separate emit() calls that can drift apart.
 */
const resolve = (value, role, context) => (
    typeof value === "function" ? value(role, context) : value
);

/**
 * Writes one notification per recipient.
 *
 * Never throws. Returns the number of rows written, which is only useful for
 * logging — no caller should branch on it.
 *
 * @param {object}   spec
 * @param {Array}    spec.audience  [{ user_id, role_id }] — from the resolvers above
 * @param {string}   spec.type      one of TYPES
 * @param {string|fn} spec.title    heading; a function receives the role id
 * @param {string|fn} spec.message  body; a function receives the role id
 * @param {string}   [spec.subject] key into LINKS, resolved per recipient role
 * @param {string|fn} [spec.link]   explicit route, overriding `subject`
 * @param {string}   [spec.priority] one of PRIORITY, default NORMAL
 * @param {number}   [spec.actorUserId] the person who caused it — never notified
 */
const emit = async ({
    audience = [],
    type,
    title,
    message,
    subject,
    link,
    priority = PRIORITY.NORMAL,
    actorUserId = null
}) => {
    try {
        if (!type || !title || !message) {
            console.warn("[notify] incomplete notification was not emitted", { type, title });
            return 0;
        }

        /*
         * Two things happen here and both matter.
         *
         * Dedupe: a parent with two children in the same class, or a teacher who
         * is also the guardian of a student, appears in an audience twice. The
         * UNION queries above already dedupe within themselves, but a caller may
         * concatenate two audiences.
         *
         * Actor removal: the person who performed the act must not be told about
         * it. Without this an admin who records a payment gets "a payment has
         * been recorded" a second later, and a teacher marking their own
         * register is notified that they marked it. That is the single fastest
         * way to train people to ignore the bell.
         */
        const seen = new Set();
        const recipients = [];

        for (const row of audience) {
            const userId = row?.user_id;
            if (!userId || userId === actorUserId || seen.has(userId)) continue;
            seen.add(userId);
            recipients.push(row);
        }

        if (!recipients.length) return 0;

        const now = new Date();

        const rows = recipients.map((row) => {
            const role = row.role_id;
            const resolvedLink = link !== undefined
                ? resolve(link, role)
                : (subject ? LINKS[subject]?.[role] ?? null : null);

            return {
                user_id: row.user_id,
                type,
                // The columns are VARCHAR(120)/(255); a long subject name or a
                // free-text reason could otherwise fail the whole insert and
                // lose every recipient's row, not just the oversized one.
                title: String(resolve(title, role)).slice(0, 120),
                message: String(resolve(message, role)).slice(0, 255),
                link: resolvedLink ? String(resolvedLink).slice(0, 255) : null,
                priority,
                is_read: false,
                created_at: now
            };
        });

        await Notification.bulkCreate(rows);

        return rows.length;

    } catch (error) {
        // Deliberately swallowed — see the header. A missing notification must
        // never fail the admission, payment or publication that triggered it.
        console.error("[notify] emission failed:", error.message);
        return 0;
    }
};

/*
 * The common shape: tell a student and their guardians about something, with
 * the guardian's copy worded in the third person.
 *
 * The caller supplies both sentences already built, because it is holding the
 * student row and the subject name anyway — resolving them here would add a
 * lookup per event for data the call site already has.
 */
const notifyStudent = async ({
    studentId,
    includeGuardians = true,
    type,
    title,
    ownMessage,
    guardianMessage,
    subject,
    priority,
    actorUserId
}) => {
    const audience = includeGuardians
        ? await studentAudience(studentId)
        : await studentOnlyAudience(studentId);

    // Carried on every row of the audience query; taken from the first because
    // they all describe the same student.
    const name = audience.length
        ? [audience[0].first_name, audience[0].last_name].filter(Boolean).join(" ")
        : "";

    // Guardians of a student whose name did not resolve still need a readable
    // sentence, so the third-person wording falls back to a generic noun rather
    // than rendering an empty possessive.
    const who = name || "your child";

    return emit({
        audience,
        type,
        title: (role) => resolve(title, role, who),
        message: (role) => (
            role === ROLES.PARENT && guardianMessage
                ? resolve(guardianMessage, role, who)
                : resolve(ownMessage, role, who)
        ),
        subject,
        priority,
        actorUserId
    });
};

